"""Index of the recipes (pipeline/recipes/README.md), generated from the header every recipe file starts with.
python tools/recipes_index.py            write the index
python tools/recipes_index.py --check    exit 1 when the index is stale (tests/test_recipes.py runs the same check)
A recipe = one file pipeline/recipes/<name>.py whose docstring starts with a title line and then, in this order,
`Use when:`, `Not for:`, `Inputs:`, `Output:`, `Checks:` (one or two lines each; a blank line ends the header).
Markdown files here stay under ~350 lines. When the index passes ~300: give every header a `Category:` line after the
title (the kind of grip: one hand, two hands, worn, thrown ...), write one README_<category>.md per category with these
tables, and let README.md list the categories with one line each."""
import ast
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECIPES = os.path.join(ROOT, "pipeline", "recipes")
INDEX = os.path.join(RECIPES, "README.md")
FIELDS = ("Use when", "Not for", "Inputs", "Output", "Checks")
# solvers that live elsewhere and are not named by `recipe` (how they are selected is in their `Inputs`): listed, not moved
ELSEWHERE = {"prop_in_hands": os.path.join(ROOT, "pipeline", "motion", "prop_in_hands.py")}


def header(path):
    """{"title", "Use when", ...} from a recipe file's docstring; ValueError names the file and what is missing."""
    doc = ast.get_docstring(ast.parse(open(path, encoding="utf-8").read()), clean=False)
    lines = (doc or "").split("\n\n")[0].splitlines()
    if not lines or not lines[0].strip(): raise ValueError("%s: no docstring title line" % path)
    out, key = {"title": lines[0].strip()}, None
    for ln in lines[1:]:
        k = next((f for f in FIELDS if ln.startswith(f + ":")), None)
        if k:
            if k in out: raise ValueError("%s: header field '%s' twice" % (path, k))
            key = k; out[k] = ln[len(k) + 1:].strip()
        elif key and ln.strip(): out[key] += " " + ln.strip()
        else: raise ValueError("%s: header line outside a field: %r" % (path, ln))
    if [k for k in out if k != "title"] != list(FIELDS):
        raise ValueError("%s: the header needs, in this order, %s (found: %s)" % (
            path, ", ".join(f + ":" for f in FIELDS), ", ".join(k for k in out if k != "title") or "none"))
    if any(not out[f] for f in FIELDS): raise ValueError("%s: empty header field" % path)
    return out


def recipes():
    """{name: (path, header)}: every pipeline/recipes/*.py plus the solvers listed in ELSEWHERE."""
    files = {os.path.splitext(os.path.basename(p))[0]: p for p in sorted(glob.glob(os.path.join(RECIPES, "*.py")))}
    return {n: (p, header(p)) for n, p in sorted({**files, **ELSEWHERE}.items())}


def names():
    """Recipe names a motion file may give in `recipe.name` (schemas/motion.schema.json lists the same)."""
    return sorted(set(recipes()) - set(ELSEWHERE))


def cell(text):
    return text.replace("|", "\\|")


def index():
    rows = ["| `%s` | %s | %s | %s |" % (n, cell(h["title"]), cell(h["Use when"]), cell(h["Not for"])) for n, (_, h) in recipes().items()]
    return "\n".join([
        "# Recipes", "",
        "Generated by `python tools/recipes_index.py` from the header of every recipe file. Do not edit: change the header.", "",
        "A recipe is one small script for one kind of grip or weapon. It runs on the merged clip in the prop step of",
        "`pipeline/chain.py` and of `character.py`'s merge stage. The motion file names it and holds its inputs:",
        "`\"recipe\": {\"name\": \"<name>\", ...}`. Choose it once, when writing the motion file. A name outside this list is a",
        "schema error. `prop_in_hands` is the one exception: experimental, frozen, selected by `actions.<a>.prop: true`.", "",
        "Read the row, then the file's header for `Inputs`, `Output` and `Checks`. Nothing fits: copy the smallest recipe",
        "into a new file, give it this header and its own rules; do not add a switch to an existing one.", "",
        "| Recipe | What | Use when | Not for |", "|---|---|---|---|", *rows, "",
        "## Writing one", "",
        "- One file `pipeline/recipes/<name>.py`; the docstring starts with a title line, then `Use when:`, `Not for:`,",
        "  `Inputs:`, `Output:`, `Checks:` in this order, one or two lines each, for a reader who has not seen the code.",
        "- Arguments `--glb <merged> --motion <motion file> --out <glb> [--skeleton X]`; success is a printed line",
        "  `RECIPE OK <out>`. It keys only the action named by the motion file and says in `Output` which bones it moves.",
        "- It writes `<out>_recipe.json` with `recipe`, `action`, `line` (one sentence of what it measured), `limits` (what",
        "  the measurement misses) and its own numbers. The audit copies it into `audit.json` and prints `line`; not scored.",
        "- Rules that need no Blender are functions above `main()`, tested on synthetic data in `tests/`; `bpy` is imported",
        "  inside `main()` so the tests can import the file.",
        "- Add the name to `recipe.name` in `schemas/motion.schema.json` with its required inputs, then run",
        "  `python tools/recipes_index.py`. `tests/test_recipes.py` fails on a stale index, a missing header or a name the",
        "  schema does not list.", ""])


if __name__ == "__main__":
    text = index()
    if "--check" in sys.argv:
        old = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if old != text: raise SystemExit("pipeline/recipes/README.md is stale: run python tools/recipes_index.py")
        print("recipes index up to date (%d recipes)" % len(recipes()))
    else:
        open(INDEX, "w", encoding="utf-8", newline="\n").write(text)
        print("wrote", INDEX, "(%d recipes)" % len(recipes()))
