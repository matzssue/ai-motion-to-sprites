"""Index of the motion playbooks (docs/motions/README.md), generated from the header every playbook starts with.
python tools/motions_index.py            write the index
python tools/motions_index.py --check    exit 1 when the index is stale (tests/test_pose_track.py runs the same check)
A playbook = one file docs/motions/<kind>.md: a `# Title` line, a blank line, then `Use when:`, `Not for:`, `Route:` in
this order (a field may run on over indented lines; a blank line ends the header), then free sections. It exists only for
a kind of motion that was made and accepted. Every file here stays under ~350 lines."""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOTIONS = os.path.join(ROOT, "docs", "motions")
INDEX = os.path.join(MOTIONS, "README.md")
FIELDS = ("Use when", "Not for", "Route")


def header(path):
    """{"title", "Use when", "Not for", "Route"} of a playbook; ValueError names the file and what is missing."""
    lines = open(path, encoding="utf-8").read().splitlines()
    if not lines or not lines[0].startswith("# ") or not lines[0][2:].strip(): raise ValueError("%s: the first line is the title: `# <kind of motion>`" % path)
    out, key = {"title": lines[0][2:].strip()}, None
    for ln in lines[2:]:
        if not ln.strip(): break
        k = next((f for f in FIELDS if ln.startswith(f + ":")), None)
        if k: key = k; out[k] = ln[len(k) + 1:].strip()
        elif key: out[key] += " " + ln.strip()
        else: raise ValueError("%s: header line outside a field: %r" % (path, ln))
    if [k for k in out if k != "title"] != list(FIELDS) or any(not out[f] for f in FIELDS):
        raise ValueError("%s: the header needs, in this order, %s (found: %s)" % (
            path, ", ".join(f + ":" for f in FIELDS), ", ".join(k for k in out if k != "title") or "none"))
    return out


def playbooks():
    """{file name without .md: header} of every docs/motions/*.md except the index."""
    return {os.path.splitext(os.path.basename(p))[0]: header(p) for p in sorted(glob.glob(os.path.join(MOTIONS, "*.md"))) if p != INDEX}


def index():
    rows = ["| [%s](%s.md) | %s | %s | %s |" % (h["title"], n, *(h[f].replace("|", "\\|") for f in FIELDS)) for n, h in playbooks().items()]
    return "\n".join([
        "# Motion playbooks", "",
        "Generated by `python tools/motions_index.py` from the header of every playbook. Do not edit: change the playbook.", "",
        "One page per kind of motion that was made with this tool and accepted by a person: which route through the tool,",
        "how many key poses, the order of the steps, what to look at before showing it, and what was tried and rejected.",
        "Read the row, then the page, before writing the motion file. The page is the route; `.claude/skills/ai-motion/SKILL.md`",
        "explains each step.", "",
        "| Motion | Use when | Not for | Route |", "|---|---|---|---|", *rows, "",
        "No row for your motion: follow the general path in the skill. Do not copy a route from a different kind of motion",
        "because it is the nearest one; say in the report that no playbook covered it.", "",
        "## Writing one", "",
        "- Only after the motion was accepted, by the session that made it, from what was measured and seen. No playbook",
        "  for a motion nobody has made: a guessed route reads the same as a proven one.",
        "- One file `docs/motions/<kind>.md` for a reader who has seen none of the work: `# Title`, a blank line, then",
        "  `Use when:`, `Not for:`, `Route:` (one or two lines each), a blank line, then the sections.",
        "- Sections, in this order: `## Route` (which part of the body comes from where, and why), `## Key poses` (how many,",
        "  on which moments), `## Steps` (commands and motion file keys in run order), `## What to look at` (which frames,",
        "  from where, how large), `## Rejected - do not retry` (one line each: what was tried, the number or the author's",
        "  words that rejected it), `## Not covered`.",
        "- Numbers come from one character: name it and say what is its own (frames, centimetres) and what is the route.",
        "- Run `python tools/motions_index.py`; `tests/test_pose_track.py` fails on a stale index or a header out of order.", ""])


if __name__ == "__main__":
    text = index()
    if "--check" in sys.argv:
        old = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if old != text: raise SystemExit("docs/motions/README.md is stale: run python tools/motions_index.py")
        print("motions index up to date (%d playbooks)" % len(playbooks()))
    else:
        open(INDEX, "w", encoding="utf-8", newline="\n").write(text)
        print("wrote", INDEX, "(%d playbooks)" % len(playbooks()))
